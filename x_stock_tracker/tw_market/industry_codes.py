def industry_label(raw: str) -> str:
    """把產業別欄位轉成可讀名稱；非數字代號就原樣回傳。"""
    value = (raw or "").strip()
    if not value:
        return ""
    if value.isdigit():
        return INDUSTRY_CODES.get(value.zfill(2), f"產業代號 {value}")
    return value
